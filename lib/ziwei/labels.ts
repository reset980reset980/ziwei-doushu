export function starLabel(name: string) {
  return STAR_LABELS[name] ?? name;
}

export function siHuaLabel(name: string) {
  return SIHUA_LABELS[name] ?? name;
}

export function stemLabel(index: number) {
  return STEM_LABELS[index] ?? '';
}

export function branchLabel(index: number) {
  return BRANCH_LABELS[index] ?? '';
}

export function ganZhiLabel(stemIndex: number, branchIndex: number) {
  return `${stemLabel(stemIndex)}${branchLabel(branchIndex)}`;
}

export function koreanizeZiweiText(value: string | undefined | null) {
  if (!value) return '';

  let text = value;

  text = text
    .replace(/(\S+?)化禄坐命，主生财顺利、人缘佳、机缘多。(\S+?)化禄属正财，宜实业、金融。/g, (_, star: string) =>
      `${starLabel(star)} 화록이 명궁에 있어 재물 흐름, 인연, 기회가 좋은 편입니다. ${starLabel(star)} 화록은 정재 성격이 강해 실업, 금융, 안정적인 수익 구조에 맞습니다.`,
    )
    .replace(/(\S+?)化禄坐命，主生财顺利、人缘佳、机缘多。(\S+?)化禄属阴财、不动产。/g, (_, star: string) =>
      `${starLabel(star)} 화록이 명궁에 있어 재물 흐름, 인연, 기회가 좋은 편입니다. ${starLabel(star)} 화록은 부동산, 축적형 자산, 조용한 재물 운과 관련이 깊습니다.`,
    )
    .replace(/(\S+?)化禄坐命，主生财顺利、人缘佳、机缘多。(\S+?)化禄属人脉财、桃花财。/g, (_, star: string) =>
      `${starLabel(star)} 화록이 명궁에 있어 재물 흐름, 인연, 기회가 좋은 편입니다. ${starLabel(star)} 화록은 사람, 매력, 네트워크를 통해 재물 통로가 열리는 성격입니다.`,
    )
    .replace(/(\S+?)化禄坐命，主生财顺利、人缘佳、机缘多。/g, (_, star: string) =>
      `${starLabel(star)} 화록이 명궁에 있어 재물 흐름, 인연, 기회가 좋은 편입니다.`,
    )
    .replace(/(\S+?)化忌坐命宫，需留意自身固执、心理障碍或健康隐患，凡事退一步思考。化忌不一定坏，代表此星能量需要特别关注。/g, (_, star: string) =>
      `${starLabel(star)} 화기가 명궁에 있어 고집, 심리적 부담, 건강상 숨은 부담을 살펴야 합니다. 화기는 반드시 나쁜 뜻만은 아니며, 해당 별의 에너지를 특별히 관리하라는 표시입니다.`,
    )
    .replace(/(\S+?)化忌坐迁移宫，外出、远行、人际关系易有波折，宜守不宜动。/g, (_, star: string) =>
      `${starLabel(star)} 화기가 천이궁에 있어 외출, 장거리 이동, 대인관계에 굴곡이 생기기 쉽습니다. 무리하게 움직이기보다 안정적으로 운용하는 편이 좋습니다.`,
    )
    .replace(/(\S+?)化权入官禄宫，主事业有掌控力、能担当独当一面的职位。化权代表权力与执行力——\S+?化权说明你在事业上能成为决策者或核心执行者，宜走管理或技术权威路线。/g, (_, star: string) =>
      `${starLabel(star)} 화권이 관록궁에 들어가 직업 영역에서 장악력과 실행력이 강해집니다. 의사결정자, 핵심 실무자, 관리직, 기술 권위형 진로에 유리합니다.`,
    )
    .replace(/(\S+?)化科入命宫，主名声、文书、学术运。倪师讲化科是「贵人星」——\S+?化科带来的是被人看重的特质，宜从事文书、教育、研究、咨询、文创等“以名取利”的方向。/g, (_, star: string) =>
      `${starLabel(star)} 화과가 명궁에 들어가 평판, 문서, 학술 운이 살아납니다. 문서, 교육, 연구, 상담, 콘텐츠처럼 이름과 신뢰로 성과를 내는 방향에 맞습니다.`,
    )
    .replace(/(\S+?)化科入身宫，主名声、文书、学术运。倪师讲化科是「贵人星」——\S+?化科带来的是被人看重的特质，宜从事文书、教育、研究、咨询、文创等“以名取利”的方向。/g, (_, star: string) =>
      `${starLabel(star)} 화과가 신궁에 들어가 평판, 문서, 학술 운이 몸의 방향성으로 드러납니다. 문서, 교육, 연구, 상담, 콘텐츠처럼 이름과 신뢰로 성과를 내는 방향에 맞습니다.`,
    )
    .replace(/(\S+?)化禄入命宫/g, (_, star: string) => `${starLabel(star)} 화록이 명궁에 들어감`)
    .replace(/(\S+?)化禄入命/g, (_, star: string) => `${starLabel(star)} 화록이 명궁에 들어감`)
    .replace(/(\S+?)化忌入命宫/g, (_, star: string) => `${starLabel(star)} 화기가 명궁에 들어감`)
    .replace(/(\S+?)化忌入命/g, (_, star: string) => `${starLabel(star)} 화기가 명궁에 들어감`)
    .replace(/(\S+?)化忌入迁/g, (_, star: string) => `${starLabel(star)} 화기가 천이궁에 들어감`)
    .replace(/(\S+?)化权入官/g, (_, star: string) => `${starLabel(star)} 화권이 관록궁에 들어감`)
    .replace(/(\S+?)化科入命宫/g, (_, star: string) => `${starLabel(star)} 화과가 명궁에 들어감`)
    .replace(/(\S+?)化科入命/g, (_, star: string) => `${starLabel(star)} 화과가 명궁에 들어감`)
    .replace(/(\S+?)化科入身宫/g, (_, star: string) => `${starLabel(star)} 화과가 신궁에 들어감`)
    .replace(/(\S+?)化科入身/g, (_, star: string) => `${starLabel(star)} 화과가 신궁에 들어감`)
    .replace(/天魁天钺夹命，男称天乙、女称玉堂，一生贵人提携。考试、求职、关键时刻常有意外贵人相助。/g,
      '천괴와 천월이 명궁 양쪽에서 도와 귀인 운이 강합니다. 시험, 구직, 중요한 선택의 순간에 예상 밖의 도움을 받기 쉽습니다.',
    )
    .replace(/天魁天钺分居命宫前后两宫/g, '천괴와 천월이 명궁 앞뒤 궁에 나뉘어 자리함');

  for (const [source, target] of PHRASE_OVERRIDES) {
    text = text.split(source).join(target);
  }

  const entries = Object.entries(TERM_LABELS).sort((a, b) => b[0].length - a[0].length);
  for (const [source, target] of entries) {
    text = text.replace(new RegExp(escapeRegExp(source), 'g'), target);
  }

  text = text
    .replace(/(.+?)화록명궁에 자리함,? 주로(.+?)$/g, '$1이 화록으로 명궁에 자리해 $2')
    .replace(/(.+?)화기명궁에 자리함,?/g, '$1 화기가 명궁에 있어 ')
    .replace(/(.+?)화기천이궁에 자리함,?/g, '$1 화기가 천이궁에 있어 ')
    .replace(/(.+?)화권관록궁에 들어감,?/g, '$1 화권이 관록궁에 들어가 ')
    .replace(/이 별 에너지/g, '이 별의 에너지')
    .replace(/들어감宫/g, '들어감')
    .replace(/代表此星能量需要/g, '이 별의 에너지는')
    .replace(/需留意/g, '주의할 점은')
    .replace(/宜走/g, '어울리는 방향은')
    .replace(/宜从事/g, '종사하기 좋은 분야는')
    .replace(/不宜/g, '피하는 편이 좋은 것은')
    .replace(/等需/g, ' 등 ')
    .replace(/的方向/g, ' 방향')
    .replace(/的行业/g, ' 분야')
    .replace(/的核心特质/g, '의 핵심 특성');

  return text
    .replace(/、/g, ', ')
    .replace(/，/g, ', ')
    .replace(/。/g, '. ')
    .replace(/；/g, '; ')
    .replace(/：「/g, ': "')
    .replace(/」/g, '"')
    .replace(/「/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}
