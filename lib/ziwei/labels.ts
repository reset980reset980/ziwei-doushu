export function koreanizeZiweiText(value: string | undefined | null) {
  if (!value) return '';

  let text = value;
  for (const [source, target] of PHRASE_OVERRIDES) {
    text = text.split(source).join(target);
  }

  const entries = Object.entries(TERM_LABELS).sort((a, b) => b[0].length - a[0].length);
  for (const [source, target] of entries) {
    text = text.replace(new RegExp(escapeRegExp(source), 'g'), target);
  }

  text = text
    .replace(/(.+?)화록명궁에 자리함,? 주로(.+?)$/g, '$1이 화록으로 명궁에 자리해 $2')
    .replace(/(.+?)화기명궁에 자리함,?/g, '$1 화기가 명궁에 있어 ')
    .replace(/(.+?)화기천이궁에 자리함,?/g, '$1 화기가 천이궁에 있어 ')
    .replace(/(.+?)화권관록궁에 들어감,?/g, '$1 화권이 관록궁에 들어가 ')
    .replace(/(.+?)화과(.+?)궁/g, '$1 화과가 $2궁')
    .replace(/이 별 에너지/g, '이 별의 에너지')
    .replace(/代表此星能量需要/g, '이 별의 에너지는')
    .replace(/需留意/g, '주의할 점은')
    .replace(/宜走/g, '어울리는 방향은')
    .replace(/宜从事/g, '종사하기 좋은 분야는')
    .replace(/不宜/g, '피하는 편이 좋은 것은')
    .replace(/等需/g, ' 등 ')
    .replace(/的方向/g, ' 방향')
    .replace(/的行业/g, ' 분야')
    .replace(/的核心特质/g, '의 핵심 특성');

  return text
    .replace(/、/g, ', ')
    .replace(/，/g, ', ')
    .replace(/。/g, '. ')
    .replace(/；/g, '; ')
    .replace(/：「/g, ': "')
    .replace(/」/g, '"')
    .replace(/「/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}
